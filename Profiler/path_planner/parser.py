MACRO_IMPORTS = """//autogenerated routine code, DO NOT TOUCH!
use crate::chassis::Chassis;
use crate::subsystems::*;
use vexide::math::*;
use vexide::prelude::*;
use alloc::rc::Rc;
use crate::helpers::*;
use crate::motion_control::ramsete::*;

pub async fn run(chassis: &Chassis) {
	let _log_task = spawn(Chassis::log_pose(Rc::clone(&chassis.pose)));
"""


def export_routine_macro(routine, code_root: str | None = None) -> Path:
    # routine is the json from routines, load it first
    # generates the rust macro to run this
    root = code_root if code_root is not None else get_code_root()
    out_path = resolve_routine_path(root, routine.get("path", ""))
    if out_path is None:
        raise ValueError("Routine path is empty or code_root is not set in settings.json")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as macro:
        macro.write(MACRO_IMPORTS)

        for action in routine["actions"]:
            # yeah this is hardcoded but idc at this point
            type = action["type"]
            if type == "start":
                macro.write(
                    f'\tchassis.set_pose(Pose::new({action["x"]}, {action["y"]}, Angle::from_degrees({action["heading"]})));\n'
                )

            if type == "motion":
                macro.write(
                    f"""\tlet mut motion{action["id"]} = MotionProfile::new("{routine["name"]}/motion{action["id"]}.json");\n\tchassis.drive_along(&mut motion{action["id"]}).await;
                """
                )
            macro.write("\n")
        macro.write("}\n")
    return out_path

